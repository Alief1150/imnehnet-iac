<?php

/**
 * Turns the installed Lucide package into a PHP icon set.
 *
 * The alternative was hand copying path data, which drifts the moment the
 * package is updated, or reaching for a Blade icon library that Filament does
 * not already have. Reading the installed package means the icons in the
 * interface are the icons in the package, and regenerating is one command.
 *
 * Run with: php tools/build-lucide-icons.php
 */
$source = __DIR__.'/../node_modules/lucide/dist/esm/icons';

if (! is_dir($source)) {
    fwrite(STDERR, "The Lucide package is not installed. Run npm install first.\n");
    exit(1);
}

/**
 * Only the icons the control plane actually uses. Keeping the set explicit
 * stops the generated file growing to every icon the package ships.
 */
$wanted = [
    'layout-dashboard', 'server', 'plus', 'play', 'square', 'rotate-ccw',
    'trash', 'trash-2', 'terminal', 'scroll-text', 'network', 'activity',
    'cpu', 'memory-stick', 'hard-drive', 'refresh-cw', 'circle-alert',
    'circle-check', 'circle-pause', 'circle-help', 'circle-question-mark',
    'loader-circle', 'snowflake', 'settings', 'circle-x', 'clock', 'gauge',
    'shield-check', 'users', 'layers', 'box', 'lock', 'wifi', 'circle-dot',

    // The Infrastructure page: four plane cards and eleven probe cards.
    //
    // These names were already in the templates while this list did not contain them.
    // An icon absent from the generated file does not render as a missing glyph — it
    // renders as an empty coloured box, which on a status card reads as a fault in the
    // page rather than a fault in the name. The fix belongs here, in the one place that
    // decides what exists, rather than as a fallback at each call site: a fallback hides
    // the next one.
    //
    // Note the spelling is the package's, not a guess — the dashboard icon is `chart-bar`,
    // not `bar-chart`, and asking for the latter produces nothing.
    'globe', 'bell', 'database', 'chart-bar', 'radio', 'boxes', 'workflow',
    'cog', 'shield', 'circle', 'shield-alert',
];

/**
 * Lucide files are ES modules whose default export is an array of
 * [tag, attributes] pairs. The shape is regular enough to read directly
 * without pulling in a JavaScript runtime.
 *
 * @return array<int, array{0: string, 1: array<string, string>}>
 */
function parseIcon(string $source): array
{
    // Matched anywhere in the file rather than anchored to the assignment. The
    // module ends with an export statement, so an anchored pattern would never
    // match, and each icon file declares exactly one shape array anyway.
    preg_match_all('/\[\s*"([a-z]+)"\s*,\s*\{([^}]*)\}\s*\]/', $source, $parts, PREG_SET_ORDER);

    $shapes = [];

    foreach ($parts as $part) {
        $attributes = [];

        if (preg_match_all('/([a-zA-Z-]+):\s*"([^"]*)"/', $part[2], $pairs, PREG_SET_ORDER) !== false) {
            foreach ($pairs as $pair) {
                $attributes[$pair[1]] = $pair[2];
            }
        }

        $shapes[] = [$part[1], $attributes];
    }

    return $shapes;
}

function render(array $shapes, string $name): string
{
    $body = '';

    foreach ($shapes as [$tag, $attributes]) {
        $rendered = '';

        foreach ($attributes as $key => $value) {
            $rendered .= sprintf(' %s="%s"', $key, htmlspecialchars($value, ENT_QUOTES));
        }

        $body .= sprintf('<%s%s/>', $tag, $rendered);
    }

    // aria-hidden because the surrounding element always carries the label as
    // text; a duplicated announcement is worse than none.
    return sprintf(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        .'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" '
        .'data-lucide="%s" class="lucide lucide-%s">%s</svg>',
        htmlspecialchars($name, ENT_QUOTES),
        htmlspecialchars($name, ENT_QUOTES),
        $body
    );
}

$icons = [];
$missing = [];

foreach ($wanted as $name) {
    $file = $source.'/'.$name.'.mjs';

    if (! is_file($file)) {
        $missing[] = $name;

        continue;
    }

    $shapes = parseIcon(file_get_contents($file) ?: '');

    if ($shapes === []) {
        $missing[] = $name;

        continue;
    }

    $icons[$name] = render($shapes, $name);
}

$php = "<?php\n\n"
    ."namespace App\\Support;\n\n"
    ."use Illuminate\\Support\\HtmlString;\n\n"
    ."/**\n"
    ." * Lucide icons, generated from the installed npm package.\n"
    ." *\n"
    ." * Generated by tools/build-lucide-icons.php. Do not edit by hand: change the\n"
    ." * wanted list there and regenerate, or the next package update will disagree\n"
    ." * with what the interface shows.\n"
    ." */\n"
    ."final class Lucide\n{\n"
    ."    /**\n"
    ."     * @return array<string, string>\n"
    ."     */\n"
    ."    public static function map(): array\n"
    ."    {\n"
    ."        return [\n";

foreach ($icons as $name => $svg) {
    $php .= "            '".$name."' => <<<'SVG'\n".$svg."\nSVG,\n";
}

$php .= "        ];\n    }\n\n"
    ."    /**\n"
    ."     * An icon as raw markup, for a component that accepts markup rather than\n"
    ."     * a component name.\n"
    ."     *\n"
    ."     * The fallback is 'circle-question-mark', which is in this file. It was\n"
    ."     * 'circle-help', which is not: that name is not in the package under this version,\n"
    ."     * so looking up a missing icon raised on the very lookup meant to absorb it. The\n"
    ."     * Infrastructure page asked for eleven names this file did not carry, and every\n"
    ."     * one of them hit that line and took the page to a 500. A safety net that throws is\n"
    ."     * not a safety net.\n"
    ."     */\n"
    ."    public static function svg(string \$name, string \$class = ''): string\n"
    ."    {\n"
    ."        return self::map()[\$name] ?? self::map()['circle-question-mark'];\n"
    ."    }\n\n"
    ."    /**\n"
    ."     * An icon as markup, or null when the name is not in the set.\n"
    ."     *\n"
    ."     * Null rather than a placeholder, deliberately. A status card showing a question\n"
    ."     * mark because someone misspelled an icon name is worse than a status card showing\n"
    ."     * no icon: the first tells the reader something that is not true, and looks like a\n"
    ."     * deliberate state. svg() keeps the fallback for places that must render something,\n"
    ."     * and callers that care check has() first.\n"
    ."     *\n"
    ."     * Returns HtmlString rather than string: the project's icon accessors —\n"
    ."     * EnvironmentStatus::icon() and the navigation icons — declare ?Htmlable, and a\n"
    ."     * bare string under those signatures is a TypeError. It was, and the environments\n"
    ."     * table 500'd on first render.\n"
    ."     */\n"
    ."    public static function icon(string \$name, string \$class = ''): ?HtmlString\n"
    ."    {\n"
    ."        \$svg = self::map()[\$name] ?? null;\n"
    ."        return \$svg === null ? null : new HtmlString(\$svg);\n"
    ."    }\n\n"
    ."    /**\n"
    ."     * An icon as markup, always, falling back to a neutral glyph.\n"
    ."     *\n"
    ."     * For the callers that are rendering a control whose presence is not in question.\n"
    ."     */\n"
    ."    public static function html(string \$name, string \$class = ''): HtmlString\n"
    ."    {\n"
    ."        return new HtmlString(self::svg(\$name, \$class));\n"
    ."    }\n\n"
    ."    /**\n"
    ."     * Whether a name is available, so a caller can hide a control rather than\n"
    ."     * render an icon that means nothing.\n"
    ."     */\n"
    ."    public static function has(string \$name): bool\n"
    ."    {\n"
    ."        return array_key_exists(\$name, self::map());\n"
    ."    }\n"
    ."}\n";

file_put_contents(__DIR__.'/../app/Support/Lucide.php', $php);

printf('Generated %d icons -> app/Support/Lucide.php%s', count($icons), PHP_EOL);

if ($missing !== []) {
    printf('Not in the package: %s%s', implode(', ', $missing), PHP_EOL);
}
